"""Generate manuscript-ready summaries from the current benchmark outputs.

The script intentionally reads only machine-readable JSON outputs.  It writes
the reconstruction and identification tables used by the appendix, the combined
identification figure used by the main paper, and ``generated/numbers.tex`` -- a
key/value file holding every figure quoted in the prose, so that re-running this
script after a new evaluation updates the manuscript text as well as its tables.

Usage:
    python scripts/paper_results.py            # tables + figure + numbers
    python scripts/paper_results.py --sync-figures   # also refresh tex/figures
"""

