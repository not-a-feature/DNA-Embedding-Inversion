# --------------------------------------------------------------------------- #
# numbers.tex
# --------------------------------------------------------------------------- #
class Numbers:
    """Collects ``key -> rendered value`` pairs for ``generated/numbers.tex``.

    Keys are dotted strings (``rec.ntv2.lev.100``); the manuscript reads them
    back with ``\\num{rec.ntv2.lev.100}``. Rendering happens here so that a
    value's precision is defined once, at the point it is computed, rather than
    being retyped at each of its use sites.
    """

    def __init__(self) -> None:
        self._values: dict[str, str] = {}

    def set(self, key: str, value: str) -> None:
        assert key not in self._values, f"Duplicate numbers key: {key}"
        self._values[key] = value

    def fixed(self, key: str, value: float, places: int = 3) -> None:
        self.set(key, f"{value:.{places}f}")

    def percent(self, key: str, value: float, places: int = 1) -> None:
        self.set(key, f"{100 * value:.{places}f}")

    def integer(self, key: str, value: int) -> None:
        # Thousands separator that survives LaTeX maths and text mode alike.
        self.set(key, f"{value:,}".replace(",", "{,}"))

    def write(self, path: Path) -> None:
        cited = set()
        for source in (TEX_DIR / "arxiv.tex", TEX_DIR / "appendix.tex"):
            prose = "\n".join(line for line in source.read_text(encoding="utf-8").splitlines() if not line.lstrip().startswith("%"))
            cited.update(re.findall(r"\\num\{([^}]+)\}", prose))
        assert cited <= self._values.keys(), ("Missing manuscript numbers", sorted(cited - self._values.keys()))
        lines = [
            "% Generated by scripts/paper_results.py; do not edit manually.",
            "% Read these with \\num{<key>} (defined in arxiv.tex).",
        ]
        for key in sorted(self._values):
            lines.append(f"\\expandafter\\def\\csname num@{key}\\endcsname{{{self._values[key]}}}")
        lines.append("")
        path.write_text("\n".join(lines), encoding="utf-8")


def _read_json(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


# --------------------------------------------------------------------------- #
# Reconstruction
# --------------------------------------------------------------------------- #
def load_reconstruction() -> dict[str, dict[int, dict]]:
    data: dict[str, dict[int, dict]] = {}
    for eval_dir in sorted(
        (ROOT / "outputs").glob("eval_multilen_seqdisjoint_*")
    ):
        for path in eval_dir.rglob("evaluation_results.json"):
            result = _read_json(path)
            assert result["inversion_model"] == "query_decoder", path
            fm = result["foundation_model"]
            assert int(result["seq_length"]) not in data.setdefault(fm, {}), path
            data.setdefault(fm, {})[int(result["seq_length"])] = result
    assert set(data) == set(FM_LABELS), data.keys()
    for fm, rows in data.items():
        assert set(rows) == LENGTHS, (fm, sorted(rows))
    return data


def write_reconstruction_table(data: dict[str, dict[int, dict]]) -> None:
    lengths = sorted(next(iter(data.values())))
    columns = "ll" + "c" * len(lengths)
    lines = [
        "% Generated by scripts/paper_results.py; do not edit manually.",
        "\\begin{table}[H]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2.6pt}",
        "\\resizebox{\\textwidth}{!}{%",
        f"\\begin{{tabular}}{{{columns}}}",
        "\\toprule",
        "\\textbf{Foundation model} & \\textbf{Metric} & "
        + " & ".join(f"\\textbf{{{length}}}" for length in lengths)
        + " \\\\",
        "\\midrule",
    ]
    for fm_index, fm in enumerate(FM_ORDER):
        if fm_index:
            lines.append("\\midrule")
        lev, acc, exact = [], [], []
        for length in lengths:
            result = data[fm][length]
            lev.append(f"{result['levenshtein_mean']:.3f} $\\pm$ {result['levenshtein_std']:.3f}")
            acc.append(f"{result['accuracy_mean']:.3f} $\\pm$ {result['accuracy_std']:.3f}")
            exact.append(f"{result['accuracy_metrics']['exact_match']:.3f}")
        lines.extend(
            [
                f"\\multirow{{3}}{{*}}{{{FM_LABELS[fm]}}} & Levenshtein similarity & "
                + " & ".join(lev)
                + " \\\\",
                " & Positionwise match rate & " + " & ".join(acc) + " \\\\",
                " & Exact-match rate & " + " & ".join(exact) + " \\\\",
            ]
        )
    lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}}",
            "\\caption{Mean-pooled reconstruction by the multi-length LCQD on "
            "50{,}000 held-out \\texttt{hg38} sequences per length. Values are mean $\\pm$ "
            "standard deviation over sequences; exact-match rate is the fraction "
            "reconstructed without any edit.}",
            "\\label{tab:query_decoder_results}",
            "\\end{table}",
            "",
        ]
    )
    (GENERATED_DIR / "reconstruction_table.tex").write_text("\n".join(lines), encoding="utf-8")


def record_reconstruction_numbers(data: dict[str, dict[int, dict]], numbers: Numbers) -> None:
    for fm, rows in data.items():
        for length, result in rows.items():
            numbers.fixed(f"rec.{fm}.lev.{length}", result["levenshtein_mean"])
            numbers.fixed(f"rec.{fm}.levsd.{length}", result["levenshtein_std"])
            numbers.fixed(f"rec.{fm}.acc.{length}", result["accuracy_mean"])
            numbers.fixed(f"rec.{fm}.accsd.{length}", result["accuracy_std"])
            exact = result["accuracy_metrics"]["exact_match"]
            numbers.fixed(f"rec.{fm}.exact.{length}", exact)
            numbers.percent(f"rec.{fm}.exactpct.{length}", exact)
            numbers.fixed(f"rec.{fm}.baselev.{length}", result["baseline_levenshtein_mean"])

        # Contiguous run of lengths whose mean Levenshtein similarity is >= 0.9;
        # the Discussion quotes its endpoints.
        strong = sorted(k for k, v in rows.items() if v["levenshtein_mean"] >= 0.90)
        numbers.set(f"rec.{fm}.strongmin", str(strong[0]) if strong else "--")
        numbers.set(f"rec.{fm}.strongmax", str(strong[-1]) if strong else "--")

    lengths = sorted(next(iter(data.values())))
    baselines = [data[fm][L]["baseline_levenshtein_mean"] for fm in data for L in lengths]
    numbers.percent("rec.baseline.min", min(baselines), places=0)
    numbers.percent("rec.baseline.max", max(baselines), places=0)
    numbers.integer("rec.ntest", int(next(iter(data.values()))[lengths[0]]["num_sequences"]))


def load_embedding_geometry() -> dict[str, dict[int, dict[str, float]]]:
    """Load Spearman correlations produced by embedding_analysis_mean.py."""
    data: dict[str, dict[int, dict[str, float]]] = {}
    for path in sorted((ROOT / "outputs").glob("analysis_mean_*/**/stats.json")):
        result = _read_json(path)
        dataset = str(result["dataset"])
        parts = dataset.split("_")
        assert len(parts) >= 2 and parts[0] in FM_LABELS, (path, dataset)
        fm = parts[0]
        length = int(parts[1])
        assert dataset == f"{fm}_{length}_hg38_multilen_seqdisjoint_mean", (path, dataset)
        assert length not in data.setdefault(fm, {}), path
        assert result["n_samples"] == 2000, path
        provenance = _read_json(path.with_name("provenance.json"))
        assert provenance["data"]["require_sequence_disjoint"], path
        data.setdefault(fm, {})[length] = {
            "cosine": float(result["spearman_corr_cosine"]),
            "euclidean": float(result["spearman_corr_euclidean"]),
        }
    assert set(data) == set(FM_ORDER), ("Missing embedding-analysis models", sorted(data))
    for fm, rows in data.items():
        assert set(rows) == LENGTHS, ("Missing embedding-analysis lengths", fm, sorted(rows))
        assert all(math.isfinite(value) for row in rows.values() for value in row.values()), fm
    return data


def record_embedding_geometry_numbers(
    data: dict[str, dict[int, dict[str, float]]], numbers: Numbers
) -> None:
    """Record embedding-geometry values directly from analysis outputs."""
    for fm, rows in data.items():
        for length, metrics in rows.items():
            for metric, value in metrics.items():
                numbers.fixed(f"emb.{fm}.spearman.{metric}.{length}", value)


def write_embedding_geometry_table(
    data: dict[str, dict[int, dict[str, float]]],
) -> None:
    """Write the Spearman table directly from embedding-analysis outputs."""
    assert set(data) == set(FM_LABELS), data.keys()
    lengths = sorted(next(iter(data.values())))
    assert all(set(rows) == set(lengths) for rows in data.values())
    metric_labels = {"cosine": "Cosine", "euclidean": "Euclidean"}
    lines = [
        "% Generated by scripts/paper_results.py; do not edit manually.",
        "\\begin{table}[H]",
        "\\centering",
        "\\resizebox{\\linewidth}{!}{%",
        "\\begin{tabular}{ll" + "c" * len(lengths) + "}",
        "\\toprule",
        "\\textbf{Model} & \\textbf{Similarity} & "
        + " & ".join(f"\\textbf{{{length}}}" for length in lengths)
        + " \\\\",
        "\\midrule",
    ]
    for fm_index, fm in enumerate(FM_ORDER):
        if fm_index:
            lines.append("\\midrule")
        for metric_index, metric in enumerate(metric_labels):
            values = []
            for length in lengths:
                value = data[fm][length][metric]
                best = max(data[other][length][metric] for other in FM_ORDER)
                rendered = f"{value:.4f}"
                if math.isclose(value, best, rel_tol=0.0, abs_tol=5e-8):
                    rendered = f"\\mathbf{{{rendered}}}"
                values.append(f"${rendered}$")
            prefix = (
                f"\\multirow{{2}}{{*}}{{{FM_LABELS[fm]}}}"
                if metric_index == 0
                else ""
            )
            lines.append(
                f"{prefix} & {metric_labels[metric]} & "
                + " & ".join(values)
                + " \\\\"
            )
    lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}}",
            "\\caption{Spearman correlation between embedding similarity (cosine / Euclidean) "
            "and sequence similarity (Levenshtein) for different models and sequence lengths.}",
            "\\label{tab:spearman_correlation}",
            "\\end{table}",
            "",
        ]
    )
    (GENERATED_DIR / "embedding_geometry_table.tex").write_text(
        "\n".join(lines), encoding="utf-8"
    )


