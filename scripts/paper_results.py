def load_identification() -> dict[str, dict]:
    data: dict[str, dict] = {}
    prefix = "identification_multilen_seqdisjoint_"
    for path in sorted((ROOT / "outputs").glob(f"{prefix}*/**/identification_results.json")):
        relative = path.relative_to(ROOT / "outputs")
        fm = relative.parts[0].removeprefix(prefix)
        assert fm not in data, ("Duplicate identification result", fm, path)
        data[fm] = _read_json(path)
    assert set(data) == set(FM_ORDER), ("Missing identification models", sorted(data))
    for fm, result in data.items():
        assert result["protocol"]["seq_length"] == 25, fm
        assert result["protocol"]["num_target_repetitions"] == 50, fm
        assert set(result["per_mode"]) == set(MODES), (fm, result["per_mode"].keys())
        for mode, row in result["per_mode"].items():
            assert row["num_individuals"] == 1000, (fm, mode)
            strict = row["strict_train_unseen_loci"]
            assert strict["num_loci"] + strict["num_excluded_loci"] == row["num_loci"], (fm, mode)
            for arm in ("oracle", "locus_blind"):
                for stratum in (row, strict):
                    curve = stratum[arm]["top1"]
                    assert {int(k) for k in curve} == set(stratum["k_grid"]), (fm, mode, arm)
                    assert curve and max(map(int, curve)) <= stratum["num_loci"], (fm, mode, arm)
                    assert all(math.isfinite(v) and 0 <= v <= 1 for v in curve.values()), (fm, mode, arm)
    return data


def _available(data: dict[str, dict]) -> tuple[str, ...]:
    """Foundation models with identification output, in the canonical order."""
    return tuple(fm for fm in FM_ORDER if fm in data)


def _threshold(curve: dict[str, float], target: float) -> str:
    for key, value in sorted(((int(k), float(v)) for k, v in curve.items())):
        if value >= target:
            return f"{key:,}".replace(",", "{,}")
    return "--"


def write_identification_table(data: dict[str, dict]) -> None:
    lines = [
        "% Generated by scripts/paper_results.py; do not edit manually.",
        "\\begin{table}[H]",
        "\\centering",
        "\\scriptsize",
        "\\begin{tabular}{lllrrrr}",
        "\\toprule",
        "\\textbf{Model} & \\textbf{Locus sampling} & \\textbf{Coordinate access} & "
        "$k_{0.5}$ & $k_{0.9}$ & $k_{0.99}$ & \\textbf{Top-1 at $k_{\\max}$} \\\\",
        "\\midrule",
    ]
    for fm in _available(data):
        for mode in MODES:
            result = data[fm]["per_mode"][mode]
            for threat, access in (("oracle", "known (Oracle)"), ("locus_blind", "unknown (alignment)")):
                curve = result[threat]["top1"]
                k_max = max(int(k) for k in curve)
                lines.append(
                    f"{FM_LABELS[fm]} & {mode.replace('_', '-')} & {access} & "
                    f"{_threshold(curve, 0.5)} & {_threshold(curve, 0.9)} & "
                    f"{_threshold(curve, 0.99)} & {curve[str(k_max)]:.3f} \\\\"
                )
    lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            "\\caption{Cohort identification for 1{,}000 individuals using length-25 "
            "reconstructions. Each point averages top-1 identification accuracy over 50 seeded random "
            "locus permutations. $k_p$ is the smallest evaluated locus budget reaching "
            "top-1 accuracy $p$; ``--'' indicates the threshold was not reached within the "
            "locus pool. $k_{\\max}$ is the largest budget evaluated for that sampling mode.}",
            "\\label{tab:identification_results}",
            "\\end{table}",
            "",
        ]
    )
    (GENERATED_DIR / "identification_table.tex").write_text("\n".join(lines), encoding="utf-8")


def record_identification_numbers(data: dict[str, dict], numbers: Numbers) -> None:
    alignment = _read_json(ROOT / "outputs/publication_metadata/alignment_diagnostics.json")
    any_mode = next(iter(data.values()))["per_mode"][MODES[0]]
    numbers.integer("id.cohort", int(any_mode["num_individuals"]))
    numbers.percent("id.chance", 1.0 / int(any_mode["num_individuals"]), places=1)

    for fm in _available(data):
        for mode in MODES:
            result = data[fm]["per_mode"][mode]
            stem = f"id.{fm}.{mode}"
            numbers.integer(f"{stem}.nloci", int(result["num_loci"]))
            hits = alignment["per_model"][fm][mode]
            assert 0 <= hits["usable_queries"] <= hits["total_queries"], (fm, mode)
            numbers.percent(f"{stem}.mappedpct", hits["usable_queries"] / hits["total_queries"])
            numbers.integer(f"{stem}.excluded", result["strict_train_unseen_loci"]["num_excluded_loci"])
            for threat in ("oracle", "locus_blind"):
                curve = {int(k): float(v) for k, v in result[threat]["top1"].items()}
                k_max = max(curve)
                tag = stem if threat == "oracle" else f"{stem}.blind"
                numbers.integer(f"{tag}.kmax", k_max)
                numbers.percent(f"{tag}.topmax", curve[k_max])
                numbers.fixed(f"{tag}.topmaxfrac", curve[k_max])
                for target, name in ((0.5, "k50"), (0.9, "k90"), (0.99, "k99")):
                    hits = [k for k in sorted(curve) if curve[k] >= target]
                    numbers.set(
                        f"{tag}.{name}",
                        f"{hits[0]:,}".replace(",", "{,}") if hits else "--",
                    )


def plot_identification(data: dict[str, dict]) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.15), sharey=True)
    panels = (("oracle", "Known loci (oracle)"), ("locus_blind", "Unknown loci (alignment-based)"))
    mode_style = {"random": ("--", "o"), "snp_enriched": ("-", "s")}
    fms = _available(data)
    for ax, (threat, title) in zip(axes, panels):
        for fm in fms:
            for mode in MODES:
                result = data[fm]["per_mode"][mode][threat]["top1"]
                points = sorted((int(k), float(v)) for k, v in result.items())
                x = np.asarray([p[0] for p in points])
                y = np.asarray([p[1] for p in points])
                linestyle, marker = mode_style[mode]
                ax.plot(
                    x,
                    y,
                    color=FM_COLORS[fm],
                    linestyle=linestyle,
                    marker=marker,
                    markersize=3.2,
                    linewidth=1.55,
                    label=f"{FM_LABELS[fm].replace('~', ' ')}; {mode.replace('_', '-')}",
                )
        ax.axhline(0.001, color="#777777", linewidth=0.8, linestyle=":", label="Chance (1/1,000)")
        ax.set_xscale("log", base=2)
        ax.set_xlim(1, 4096)
        ax.set_ylim(0, 1.02)
        ax.set_title(title, fontsize=9.5)
        ax.set_xlabel("Number of loci, $k$")
        ax.grid(True, which="major", alpha=0.23, linewidth=0.6)
    axes[0].set_ylabel("Top-1 identification accuracy")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=3, frameon=False, fontsize=7.4)
    fig.tight_layout(rect=(0, 0.16 if len(fms) < 3 else 0.22, 1, 1), w_pad=2.2)
    FIGURE_DIR.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIGURE_DIR / "identification_top1_vs_k.pdf", bbox_inches="tight")
    fig.savefig(FIGURE_DIR / "identification_top1_vs_k.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


# --------------------------------------------------------------------------- #
# Figure sync
# --------------------------------------------------------------------------- #
def sync_figures() -> None:
    """Copy freshly produced PDFs from outputs/ into tex/figures/."""
    copied = 0
    for src_rel, dst_rel in FIGURE_SYNC:
        src = ROOT / src_rel
        assert src.is_dir(), f"Missing figure source: {src}"
        dst = FIGURE_DIR / dst_rel
        dst.mkdir(parents=True, exist_ok=True)
        pdfs = sorted(src.rglob("*.pdf"))
        assert pdfs, f"No PDFs in {src}"
        for pdf in pdfs:
            target = dst / pdf.relative_to(src)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(pdf, target)
            copied += 1
        print(f"  [ok]   {src_rel} -> figures/{dst_rel}")
    print(f"Synced {copied} PDF(s) into {FIGURE_DIR}")


# --------------------------------------------------------------------------- #
def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--sync-figures",
        action="store_true",
        help="also copy PDFs from outputs/ into tex/figures/",
    )
    args = parser.parse_args()

    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    numbers = Numbers()

    reconstruction = load_reconstruction()
    embedding_geometry = load_embedding_geometry()
    identification = load_identification()
    corpus = _read_json(ROOT / "outputs/publication_metadata/hg38-source-metadata.json")
    assert corpus["attributes"]["schema"] == "dna_inversion_hg38_multilen_v2"
    assert corpus["attributes"]["sequence_content_split_disjoint"] == "True"
    held_out = int(corpus["attributes"]["val_size_per_length"]) + int(corpus["attributes"]["test_size_per_length"])
    for length in sorted(LENGTHS):
        n_train = corpus["lengths"][str(length)]["rows"] - held_out
        assert 0 < n_train <= 4**length, (length, n_train)
        numbers.percent(f"coverage.{length}", n_train / 4**length, places=3)
    write_reconstruction_table(reconstruction)
    record_reconstruction_numbers(reconstruction, numbers)
    record_embedding_geometry_numbers(embedding_geometry, numbers)
    write_embedding_geometry_table(embedding_geometry)

    print(f"Identification models found: {', '.join(_available(identification))}")
    write_identification_table(identification)
    record_identification_numbers(identification, numbers)
    plot_identification(identification)

    numbers.write(GENERATED_DIR / "numbers.tex")
    print(f"Wrote {GENERATED_DIR / 'numbers.tex'}")

    if args.sync_figures:
        sync_figures()


if __name__ == "__main__":
    main()
